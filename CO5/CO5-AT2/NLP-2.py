# Text Coherence

s1 = "The roads were flooded after heavy rainfall."
s2 = "Therefore, schools were closed for the day."
s3 = "Students attended classes online."

print("Discourse Relations:")
print("S1 -> S2 : Cause-Effect")
print("S2 -> S3 : Sequence / Elaboration")

print("\nDiscourse Structure:")
print("Rainfall -> Flooded Roads")
print("Flooded Roads -> Schools Closed")
print("Schools Closed -> Online Classes")

print("\nCoherence:")
print("Each sentence logically follows the previous sentence.")
