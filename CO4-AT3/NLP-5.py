print("TRANSITION-BASED vs GRAPH-BASED PARSING")

print("\nTransition-Based:")
print("Builds dependency tree step by step.")
print("Fast and efficient.")
print("Suitable for large datasets.")

print("\nGraph-Based:")
print("Scores possible dependency trees.")
print("Usually more computationally expensive.")
print("Can provide globally optimized trees.")

print("\nComparison:")
print("Transition-Based -> Faster")
print("Graph-Based -> Global optimization")

print("\nConclusion:")
print("Transition-based parsing is more suitable")
print("for large-scale real-time applications.")
