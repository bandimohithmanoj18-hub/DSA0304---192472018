print("CFG vs DEPENDENCY PARSING")

print("\nCFG:")
print("Represents sentences as a tree of phrases.")
print("Example: S -> NP + VP")

print("\nDependency Parsing:")
print("Represents relationships between words.")
print("Example: saw -> She, man")

print("\nComparison:")
print("CFG -> Focuses on phrase structure")
print("Dependency -> Focuses on word relationships")

print("\nConclusion:")
print("Dependency parsing is better for capturing")
print("relationships between individual words.")
