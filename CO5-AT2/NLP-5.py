# Hybrid Machine Translation

source = "The boy is playing football."

print("Source Sentence:")
print(source)

print("\nInterlingua:")
print("boy + PLAY + football + present_continuous")

print("\nCandidate Translations:")
print("1. The boy is playing football.")
print("2. The boy plays football.")

print("\nStatistical Scoring:")
print("Candidate 1 = 0.92")
print("Candidate 2 = 0.65")

print("\nFinal Translation:")
print("The boy is playing football.")

